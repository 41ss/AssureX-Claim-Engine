"""Writes data/dataset_statistics.md from the generated CSVs. Numbers come from the data, never typed by hand."""
from pathlib import Path

import pandas as pd

DATA_DIR = Path(__file__).resolve().parents[1] / "data"


def block(title, text):
    return f"## {title}\n\n```\n{text}\n```\n"


def main():
    splits = {name: pd.read_csv(DATA_DIR / f"claims_{name}.csv") for name in ("train", "val", "test")}

    lines = ["# Dataset statistics\n", "Generated by `dataset_generator/report.py`. Never hand-edited.\n"]

    lines.append(block("Row counts", "\n".join(f"{n}: {len(df)}" for n, df in splits.items())))

    for name, df in splits.items():
        lines.append(block(f"Label distribution — {name}", df["label"].value_counts().to_string()))

    lines.append(block("Scenario distribution (train)", splits["train"]["scenario"].value_counts().to_string()))
    lines.append(block("Product category distribution (train)", splits["train"]["product_category"].value_counts().to_string()))
    numeric_train = splits["train"].select_dtypes(include="number")
    lines.append(block("Numeric feature summary (train)", numeric_train.describe().round(2).to_string()))

    all_codes = pd.concat([df["claim_code"] for df in splits.values()])
    lines.append(block("Claim ID uniqueness",
        f"total claims: {len(all_codes)}\nunique claim codes: {all_codes.nunique()}\nduplicates: {len(all_codes) - all_codes.nunique()}"))

    (DATA_DIR / "dataset_statistics.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote data/dataset_statistics.md")


if __name__ == "__main__":
    main()